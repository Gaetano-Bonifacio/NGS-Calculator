// Builds index.html and artifact_logic.mjs from ngs_calculator.jsx (the single source of truth).
// Usage: npm install && npm run build   (then npm run verify)
import { readFileSync, writeFileSync } from "node:fs";
import { transformSync } from "@babel/core";

const SRC = "ngs_calculator.jsx";
const jsx = readFileSync(SRC, "utf8");

/* 1. Testable logic module: calculation logic plus seeded data and scenario helpers */
const start = jsx.indexOf("const ROBOT_MODELS =");
const end = jsx.indexOf("/* ============================ FORMATTERS");
if (start < 0 || end < 0) throw new Error("Logic markers not found in " + SRC);
const logic = "// GENERATED by build.mjs from ngs_calculator.jsx. Do not edit by hand.\n" +
  jsx.slice(start, end) +
  "\nexport { ROBOT_MODELS, EPS, ceilSafe, nn, perSample, years, maxPerFlowcell, minDepthForVaf, coverageCheck, routine, model, SEED_BUNDLES, SEED_SEQUENCERS, SEED_ROBOTS, defaultScenario, normalizeScenario, COPYRIGHT, SCHEMA };\n";
writeFileSync("artifact_logic.mjs", logic);

/* 2. Browser bundle: strip ES module syntax, compile JSX ahead of time (no in-browser Babel) */
const body = jsx
  .replace(/^import .*$/gm, "")
  .replace("export default function NGSCalculator", "function NGSCalculator");
const compiled = transformSync(body, { presets: [["@babel/preset-react", { runtime: "classic" }]], babelrc: false, configFile: false, comments: false }).code;
